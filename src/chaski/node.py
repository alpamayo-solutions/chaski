"""``chaski.Node``: an embedded colcad.

A ``Node`` is a node like any other:
colcad plus the services publishing through its local door. Configuration is
generated by the SDK, never written by the integrator — loopback addresses on
high ports, a data directory under the caller's home, no TLS doors except the
uplink, ``autobind: on_new_connector``. Because the child opens the uplink
outbound and commands ride the same link, an embedded node needs no inbound
port — which is also why it has no ``/healthz`` a remote operator can reach:
enrollment reads the pubkey locally instead, and :meth:`Node.enroll_hint`
says what the operator of the PARENT does with it.

``parent`` accepts three shapes:

- ``None`` — a root, or a node not yet given a parent at all.
- a bare URL string — trust-on-first-use: the parent's pubkey is read once
  from its unauthenticated ``GET /healthz`` and pinned into the data
  directory. Every later ``start()`` re-checks that URL still presents the
  same key and refuses a mismatch (the standard SSH TOFU contract: the trust
  DECISION is made once, but a changed key is never accepted silently).
- ``(url, pubkey)`` — an explicit pin: the parent's REPLICATION door as
  reachable from here and its pubkey, the two values the parent's operator
  hands out, used verbatim (a host process behind a port remap cannot derive
  that door from the parent's own address). This IS the re-pin mechanism a
  mismatch error tells the caller to use.
"""

